#!/usr/bin/env python3
"""Generate explicit fieldwise readers from the public header; fail on unknown syntax.
No C struct byte comparison, pointer addresses, or inactive union storage is read.
"""
import hashlib, pathlib, re
HERE=pathlib.Path(__file__).resolve().parent
NATIVE=HERE.parents[1]
header=NATIVE/'include/aether/aether.h'
raw=header.read_text()
s=re.sub(r'/\*.*?\*/','',raw,flags=re.S)
def fields(body):
    out=[]
    for decl in body.split(';'):
        decl=decl.strip()
        if not decl: continue
        m=re.fullmatch(r'(\w+)\s*(\*)?\s+(.+)',decl, re.S)
        if not m: raise ValueError(decl)
        typ,ptr,names=m.groups()
        for name in names.split(','):
            name=name.strip()
            n=re.fullmatch(r'(\w+)(\[\d+\])?',name)
            if not n: raise ValueError(name)
            out.append((typ, bool(ptr), n[1],n[2]))
    return out
structs={name:fields(body) for body,name in re.findall(r'typedef\s+struct\s*\{([^{}]*)\}\s*(\w+)\s*;',s)}
needed=[]
def include(name):
    if name in needed:return
    for typ,ptr,n,arr in structs[name]:
        if typ in structs:include(typ)
    needed.append(name)
include('aether_computed_style_t')
command_body=s[s.index('aether_paint_command_tag_t tag;'):s.index('} aether_paint_command_t;')]
arms={n:fields(b) for b,n in re.findall(r'struct\s*\{([^{}]*)\}\s*(\w+)\s*;',command_body)}
for fs in arms.values():
    for typ,_,_,_ in fs:
        if typ in structs:include(typ)
manifest={name:fs for name,fs in structs.items() if name in needed}
manifest['paint_command_active_arms']=arms
import json
(HERE/'field_manifest.json').write_text(json.dumps({'header_sha256':hashlib.sha256(header.read_bytes()).hexdigest(),'types':manifest},indent=2)+'\n')
out=['// Generated by generate.py from the public ABI. Do not hand edit.\n']
def emit(fs,prefix='v',path='p'):
    lines=[]
    for typ,ptr,n,arr in fs:
        expr=f'{prefix}.{n}'; key=f'{path}+".{n}"'
        if ptr and typ!='char':
            count='stop_count' if n=='stops' else 'count'
            lines += [f'  sequence(w, {key}, {expr}, {prefix}.{count});']
        else:lines += [f'  value(w, {key}, {expr});']
    return lines
for name in needed:
    out += [f'inline void value(Writer& w, const std::string& p, const {name}& v) {{']+emit(structs[name])+['}']
out+=['inline void value(Writer& w, const std::string& p, const aether_paint_command_t& v) {','  value(w,p+".tag",v.tag);','  switch(v.tag) {']
for name,fs in arms.items():
    tags=['BEGIN_PAINT_CHUNK','END_PAINT_CHUNK'] if name=='paint_chunk' else [name.upper()]
    out += [f'  case AETHER_PAINT_{t}:' for t in tags]
    out+=emit(fs,'v.data.'+name,'p+".data.'+name+'"')+['    break;']
for name in ['POP_CLIP','POP_TRANSFORM','POP_SCROLL_OFFSET']:out += [f'  case AETHER_PAINT_{name}: break;']
out+=['  default: throw std::runtime_error("unknown public command tag");','  }','}']
(HERE/'fields.generated.h').write_text('\n'.join(out)+'\n')
base=(NATIVE/'tests/test_flexbox_page.cpp').read_text()
assert base.count('int main(int argc, char** argv) {')==1
base=base.replace('int main(int argc, char** argv) {','#include "snapshot.h"\nint main(int argc, char** argv) {')
needle='        report << "display_commands=" << commands << \'\\n\';'
assert base.count(needle)==1
base=base.replace(needle,needle+'\n        semantic_snapshot(p.styles, p.list, all, p.updates, p.update_count, std::filesystem::path(argv[2]) / "semantic.txt");')
(HERE/'page.generated.cpp').write_text('// Generated instrumentation-only copy; never use for timing.\n'+base)
print('Generated',len(needed),'struct serializers;',len(arms),'active command arms')
# Exhaustive mutation controls: initialize every nested dynamic list with one
# item, then perturb each semantic scalar/string/count leaf separately.
control=['// Generated exhaustive leaf sensitivity controls. No engine mutation.', '#include <aether/aether.h>','#include <filesystem>','#include <cstring>','#include <sstream>','#include <iostream>','#include "snapshot.h"','template<class T> std::string dump(const T& v) { std::ostringstream s; Writer w{s}; value(w,"value",v); return s.str(); }','int main() { int checks=0; int failures=0;']
serial=0
def setup(fs,expr):
    global serial
    init=[]; leaves=[]
    for typ,ptr,n,arr in fs:
        e=expr+'.'+n
        if ptr:
            serial+=1; local='storage'+str(serial)
            if typ=='char':
                init += [f'char {local}[]="a"; {e}={local};'];leaves += [(e+'[0]',False)]
            else:
                init += [f'{typ} {local}[1]{{}}; {e}={local};']
                more,ls=setup(structs[typ],e+'[0]'); init+=more;leaves+=ls
                count='stop_count' if n=='stops' else 'count'
                init += [expr+'.'+count+'=1;']
        elif arr:leaves += [(e+'[0]',False)]
        elif typ in structs:
            more,ls=setup(structs[typ],e);init+=more;leaves+=ls
        else:leaves += [(e, n in ('count','stop_count'))]
    return init,leaves
cases=[(n,fs,None) for n,fs in structs.items() if n in needed]
for name,fs in arms.items():cases.append(('aether_paint_command_t',fs,name))
for typ,fs,arm in cases:
    control += ['{',typ+' v{};']
    expr='v'
    if arm:
        tag='BEGIN_PAINT_CHUNK' if arm=='paint_chunk' else arm.upper()
        control += ['v.tag=AETHER_PAINT_'+tag+';'];expr+=' .data.'+arm
    init,leaves=setup(fs,expr);control+=init
    control+=['const auto original=dump(v);']
    for leaf,is_count in leaves:
        control += ['{',f'auto old={leaf};',f'{leaf}='+('0' if is_count else 'static_cast<decltype(old)>(old+1)')+';', '++checks; if(dump(v)==original) { ++failures; std::cerr << "missed '+leaf+'\\n"; }',f'{leaf}=old;','}']
    control+=['}']
control+=['std::cout << "leaf mutation checks=" << checks << " failures=" << failures << "\\n"; return failures?1:0;','}']
(HERE/'sensitivity.generated.cpp').write_text('\n'.join(control)+'\n')
